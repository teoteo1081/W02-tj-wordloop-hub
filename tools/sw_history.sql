-- Gọn: chỉ chữ (~0,5–1 KB/bài); app giữ tối đa 50 bài gần nhất/người và xoá bài quá 90 ngày (xem learn/sw/sw.js: revCloudLoad).
-- Chạy 1 lần trong Supabase SQL Editor (hoặc qua Management API). Cùng quy ước phân quyền với game_answers (shared_all).
create table if not exists public.sw_history (
  id        bigint generated by default as identity primary key,
  player_id uuid   not null references public.game_players(id) on delete cascade,
  ts        bigint not null,                 -- Date.now() lúc chấm (cũng dùng chống trùng)
  kind      text   not null check (kind in ('speaking','writing')),
  set_id    text   not null,                 -- mã đề trong learn/sw/sets.json
  q         int    not null,
  type      text,
  pm        text,                            -- đề rút gọn (đề riêng nạp từ file không có trong sets.json)
  score     int,
  max       int,
  ans       text,
  s         jsonb,                           -- điểm mạnh
  f         jsonb,                           -- cần sửa
  better    text,
  live      boolean not null default false,  -- làm trong lớp trực tiếp
  unique (player_id, ts)
);
create index if not exists sw_history_player_idx on public.sw_history (player_id, ts desc);
alter table public.sw_history enable row level security;
drop policy if exists shared_all on public.sw_history;
create policy shared_all on public.sw_history for all to anon, authenticated using (true) with check (true);
